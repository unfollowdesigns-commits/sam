/**
 * Generates the responsive derivatives every photograph is actually served as.
 *
 * The originals are up to 1800px and up to 670KB each. A phone was being sent
 * all of it — 38 frames, 6.7MB — to paint into a column about 350px wide. The
 * blurred placeholder is meant to cover a moment; at those weights it covers
 * long enough to look like the photograph never arrived.
 *
 * So each frame is written out at several widths in AVIF and WebP, and the
 * browser picks. The original JPEG stays as the last fallback and as the file
 * the structured data and the sitemap point at, so nothing that quotes this
 * work has to know about any of this.
 *
 * AVIF is here because these are film scans: grain is the worst case for
 * WebP, which on the heaviest frame saves almost nothing, while AVIF still
 * takes a quarter off.
 *
 * Run after adding or replacing photographs (it skips what is already built,
 * so re-running is cheap):
 *   node tools/build-responsive.mjs
 */
import sharp from 'sharp';
import { readdirSync, mkdirSync, existsSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const IMAGES = join(ROOT, 'images');
const OUT = join(IMAGES, 'r');

/**
 * The widths a frame is ever painted at, across every layout this site has.
 * 1800 is here because the feature plate runs the full viewport width: capped
 * at 1440 it was being stretched, which is exactly the softness the
 * derivatives were meant to remove.
 */
export const WIDTHS = [480, 960, 1440, 1800];

const FORMATS = [
  ['avif', (p) => p.avif({ quality: 55, effort: 4 })],
  ['webp', (p) => p.webp({ quality: 74, effort: 5 })],
];

mkdirSync(OUT, { recursive: true });

const sources = readdirSync(IMAGES)
  .filter((f) => /\.jpe?g$/i.test(f) && f !== 'og.jpg')
  .sort();

let built = 0;
let skipped = 0;
let before = 0;
const manifest = {};

for (const file of sources) {
  const stem = basename(file, extname(file));
  const src = join(IMAGES, file);
  const meta = await sharp(src).metadata();
  before += statSync(src).size;

  // Never upscale — a 562px frame gets one derivative, not three blurry ones —
  // but always offer the native width as the top rung. Without it a frame
  // whose width falls between two ladder steps tops out below its own size,
  // and the browser stretches a derivative when a sharper file existed.
  const widths = [...new Set([...WIDTHS.filter((w) => w < meta.width), meta.width])];

  manifest[`images/${file}`] = { width: meta.width, height: meta.height, widths };

  for (const w of widths) {
    for (const [ext, encode] of FORMATS) {
      const out = join(OUT, `${stem}-${w}.${ext}`);
      if (existsSync(out) && statSync(out).mtimeMs > statSync(src).mtimeMs) { skipped++; continue; }
      await encode(sharp(src).resize({ width: w, withoutEnlargement: true })).toFile(out);
      built++;
    }
  }
}

writeFileSync(join(ROOT, 'js', 'sizes.js'),
  `/**\n * Generated by tools/build-responsive.mjs — do not edit by hand.\n *\n`
  + ` * For each photograph: its real pixel size, and the widths that were\n`
  + ` * actually written into images/r/. The grid builds its srcset from this,\n`
  + ` * so it never offers the browser a file that is not there.\n */\n`
  + `export const SIZES = ${JSON.stringify(manifest, null, 2)};\n`);

const after = readdirSync(OUT).reduce((n, f) => n + statSync(join(OUT, f)).size, 0);
const smallest = readdirSync(OUT).filter((f) => f.includes('-480.avif'))
  .reduce((n, f) => n + statSync(join(OUT, f)).size, 0);

console.log(`built ${built} derivatives, ${skipped} already current`);
console.log(`originals        ${(before / 1024 / 1024).toFixed(1)} MB`);
console.log(`derivatives      ${(after / 1024 / 1024).toFixed(1)} MB on disk (the browser takes one per frame)`);
console.log(`a phone now gets ${(smallest / 1024 / 1024).toFixed(2)} MB for the whole gallery at 480px AVIF`);
